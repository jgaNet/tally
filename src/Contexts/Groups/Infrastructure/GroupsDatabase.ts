import { randomBytes } from 'node:crypto';

import {
  PostgresDatabase,
  PostgresTables,
  databaseUrl,
} from '@Architecture/Infrastructure/DataSources/PostgresDatabase';

/**
 * The tables the Groups context keeps its accounts, its groups, its invitations and its signing key in, in the database at
 * `DATABASE_URL`. Several servers may use the same database: its writes take turns (see `PostgresDatabase`), and its reads see
 * what is committed.
 */
export class GroupsDatabase extends PostgresTables {
  constructor(urlOf: () => string = databaseUrl) {
    super(urlOf, setUp);
  }
}

/** The tables of the groups, made once (idempotent). The signing key is made once too, by the first set-up, and kept. */
async function setUp(database: PostgresDatabase): Promise<void> {
  await database.query(`
    CREATE TABLE IF NOT EXISTS accounts (
      id TEXT PRIMARY KEY,
      email TEXT NOT NULL UNIQUE,
      name TEXT NOT NULL,
      password_hash TEXT NOT NULL
    );
    ALTER TABLE accounts ADD COLUMN IF NOT EXISTS version INTEGER NOT NULL DEFAULT 1;
    ALTER TABLE accounts ADD COLUMN IF NOT EXISTS suspended_at TEXT;
    CREATE TABLE IF NOT EXISTS account_administrator_log (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id TEXT NOT NULL UNIQUE,
      decided_at TEXT NOT NULL,
      by_account TEXT NOT NULL,
      action TEXT NOT NULL,
      subject_id TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS expense_groups (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY,
      id TEXT PRIMARY KEY,
      name TEXT NOT NULL,
      currency TEXT NOT NULL,
      owner_id TEXT NOT NULL,
      created_at TEXT NOT NULL,
      version INTEGER NOT NULL DEFAULT 1,
      archived_at TEXT,
      merged_into TEXT
    );
    ALTER TABLE expense_groups ADD COLUMN IF NOT EXISTS merged_into TEXT;
    CREATE TABLE IF NOT EXISTS expense_group_members (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY,
      group_id TEXT NOT NULL REFERENCES expense_groups (id) DEFERRABLE INITIALLY DEFERRED,
      account_id TEXT NOT NULL,
      joined_at TEXT NOT NULL DEFAULT '',
      PRIMARY KEY (group_id, account_id)
    );
    CREATE INDEX IF NOT EXISTS expense_group_members_by_account ON expense_group_members (account_id);
    CREATE TABLE IF NOT EXISTS expense_group_passes (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      group_id TEXT NOT NULL REFERENCES expense_groups (id) DEFERRABLE INITIALLY DEFERRED,
      from_account TEXT NOT NULL,
      to_account TEXT NOT NULL,
      amount INTEGER NOT NULL,
      passed_at TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS expense_group_passes_by_group ON expense_group_passes (group_id);
    CREATE TABLE IF NOT EXISTS invitations (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY,
      id TEXT PRIMARY KEY,
      group_id TEXT NOT NULL REFERENCES expense_groups (id) DEFERRABLE INITIALLY DEFERRED,
      invited_by TEXT NOT NULL,
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS settings (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL
    );
  `);
  await database.query("INSERT INTO settings (key, value) VALUES ('token_key', $1) ON CONFLICT DO NOTHING", [
    randomBytes(32).toString('base64url'),
  ]);
}
