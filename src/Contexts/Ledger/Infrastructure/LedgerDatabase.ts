import {
  PostgresDatabase,
  PostgresTables,
  databaseUrl,
} from '@Architecture/Infrastructure/DataSources/PostgresDatabase';

/**
 * The tables the Ledger context keeps its expenses in, in the database at `DATABASE_URL`, under tables of its own (ADR 5). Several
 * servers may use the database: its writes take turns, and its reads see what is committed.
 */
export class LedgerDatabase extends PostgresTables {
  constructor(urlOf: () => string = databaseUrl) {
    super(urlOf, setUp);
  }
}

/** The tables of the ledger, made once (idempotent). A file of an earlier layout is brought to this one when it is moved (see the bootstrap). */
async function setUp(database: PostgresDatabase): Promise<void> {
  await database.query(`
    CREATE TABLE IF NOT EXISTS ledger_expenses (
      id TEXT PRIMARY KEY,
      group_id TEXT NOT NULL,
      description TEXT NOT NULL,
      amount INTEGER NOT NULL,
      date TEXT NOT NULL,
      paid_by TEXT NOT NULL,
      version INTEGER NOT NULL DEFAULT 1,
      split_kind TEXT NOT NULL DEFAULT 'equal',
      recorded_seq INTEGER NOT NULL,
      recorded_at TEXT NOT NULL DEFAULT '',
      original_currency TEXT,
      original_amount INTEGER,
      original_rate TEXT,
      category TEXT NOT NULL DEFAULT 'other'
    );
    CREATE INDEX IF NOT EXISTS ledger_expenses_by_group ON ledger_expenses (group_id);
    CREATE TABLE IF NOT EXISTS ledger_expense_shares (
      expense_id TEXT NOT NULL REFERENCES ledger_expenses (id) DEFERRABLE INITIALLY DEFERRED,
      position INTEGER NOT NULL,
      member_id TEXT NOT NULL,
      amount INTEGER NOT NULL,
      PRIMARY KEY (expense_id, position)
    );
    CREATE TABLE IF NOT EXISTS ledger_recurring_expenses (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY,
      id TEXT PRIMARY KEY,
      group_id TEXT NOT NULL,
      paid_by TEXT NOT NULL,
      description TEXT NOT NULL,
      amount INTEGER NOT NULL,
      starts_on TEXT NOT NULL,
      next TEXT NOT NULL,
      split_kind TEXT NOT NULL,
      version INTEGER NOT NULL DEFAULT 1,
      category TEXT NOT NULL DEFAULT 'other'
    );
    CREATE INDEX IF NOT EXISTS ledger_recurring_by_group ON ledger_recurring_expenses (group_id);
    CREATE TABLE IF NOT EXISTS ledger_recurring_shares (
      recurring_id TEXT NOT NULL REFERENCES ledger_recurring_expenses (id) DEFERRABLE INITIALLY DEFERRED,
      position INTEGER NOT NULL,
      member_id TEXT NOT NULL,
      share_value INTEGER NOT NULL,
      PRIMARY KEY (recurring_id, position)
    );
    CREATE TABLE IF NOT EXISTS ledger_budgets (
      id TEXT PRIMARY KEY,
      group_id TEXT NOT NULL,
      category TEXT NOT NULL,
      amount INTEGER,
      version INTEGER NOT NULL,
      UNIQUE (group_id, category)
    );
    CREATE TABLE IF NOT EXISTS ledger_budget_passed_months (
      budget_id TEXT NOT NULL REFERENCES ledger_budgets (id) DEFERRABLE INITIALLY DEFERRED,
      month TEXT NOT NULL,
      PRIMARY KEY (budget_id, month)
    );
    CREATE TABLE IF NOT EXISTS ledger_split_templates (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY,
      id TEXT PRIMARY KEY,
      group_id TEXT NOT NULL,
      name TEXT NOT NULL,
      name_key TEXT NOT NULL,
      split_kind TEXT NOT NULL,
      saved_by TEXT NOT NULL,
      version INTEGER NOT NULL,
      UNIQUE (group_id, name_key)
    );
    CREATE TABLE IF NOT EXISTS ledger_split_template_lines (
      template_id TEXT NOT NULL REFERENCES ledger_split_templates (id) DEFERRABLE INITIALLY DEFERRED,
      position INTEGER NOT NULL,
      member_id TEXT NOT NULL,
      shares INTEGER,
      PRIMARY KEY (template_id, position)
    );
    CREATE TABLE IF NOT EXISTS ledger_receipts (
      id TEXT PRIMARY KEY,
      expense_id TEXT NOT NULL UNIQUE,
      type TEXT NOT NULL,
      size INTEGER NOT NULL,
      url TEXT NOT NULL,
      version INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS ledger_audit_entries (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id TEXT NOT NULL UNIQUE,
      group_id TEXT NOT NULL,
      at TEXT NOT NULL,
      by_account TEXT NOT NULL,
      action TEXT NOT NULL,
      subject_id TEXT NOT NULL,
      amount INTEGER NOT NULL
    );
    CREATE INDEX IF NOT EXISTS ledger_audit_by_group ON ledger_audit_entries (group_id);
    CREATE TABLE IF NOT EXISTS ledger_balances (
      group_id TEXT NOT NULL,
      member_id TEXT NOT NULL,
      balance INTEGER NOT NULL,
      PRIMARY KEY (group_id, member_id)
    );
  `);
}
