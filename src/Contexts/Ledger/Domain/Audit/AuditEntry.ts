import { Id } from '@Architecture/Domain';

/**
 * What a change of money is, as the audit names it (request 28). Ledger writes the first three, of its own expenses; the other four
 * are read through Settlements' and Groups' ports and kept by them, in their own words, under the same public names.
 */
export type AuditAction =
  | 'expense-recorded'
  | 'expense-edited'
  | 'expense-deleted'
  | 'settlement-paid'
  | 'settlement-refunded'
  | 'settlement-contested'
  | 'balance-passed';

/**
 * An entry of a group's audit (request 28): who made the change (`by`, an account), when (`at`), what (`action`, about `subjectId`), and how
 * much (`amount`). A plain value, never changed once it is written: nothing removes or edits one. It is the read model the audit is read
 * with as well.
 */
export interface AuditEntry {
  id: string;
  at: string;
  by: string;
  action: AuditAction;
  subjectId: string;
  amount: number;
}

/**
 * The entry a change records, made at the time the change is decided, with its own id generated by the domain (DOMAIN-IDENTITY): the
 * entry is a fact, not a thing another context keeps an identity for.
 */
export const auditEntryOf = (
  change: { by: string; action: AuditAction; subjectId: string; amount: number },
  at: Date,
): AuditEntry => ({
  id: Id.generate().value,
  at: at.toISOString(),
  by: change.by,
  action: change.action,
  subjectId: change.subjectId,
  amount: change.amount,
});
