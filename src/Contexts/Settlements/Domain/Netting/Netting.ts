import { AggregateRoot, Id, IResult, Result } from '@Architecture/Domain';
import { CURRENCIES } from '@SharedKernel/Domain/Currency';

import { NettingRecordedEvent } from '@Contexts/Settlements/Domain/Netting/Events/NettingEvents';
import {
  NettingWithSelfException,
  NothingToNetException,
  UnsupportedNettingCurrencyException,
} from '@Contexts/Settlements/Domain/Netting/NettingExceptions';

/** What a netting is made of: who asked (`by`), with whom (`with`), the currency, the amount netted, and its settlements' ids in order. */
export interface NettingDraft {
  by: string;
  with: string;
  currency: string;
  amount: number;
  settlements: string[];
}

/**
 * What two members owe each other across their groups, netted in one currency (request 32, docs/adr/0032). Small: it keeps what the
 * netting is and the settlements it made, which the two members read. It is never changed: its settlements are the books' and count
 * as any settlement does. Its identity is generated by the domain (DOMAIN-IDENTITY).
 *
 * `create()` validates the draft and records `NettingRecorded`; a netting with oneself, in a currency that is not one of Tally's, or
 * that nets nothing, is refused. There is no `fromSnapshot()`: a netting is only read by its queries, never loaded to be changed.
 */
export class Netting extends AggregateRoot {
  #by: string;
  #with: string;
  #currency: string;
  #amount: number;
  #settlements: string[];

  private constructor(id: Id, draft: NettingDraft) {
    super(id, 0);
    this.#by = draft.by;
    this.#with = draft.with;
    this.#currency = draft.currency;
    this.#amount = draft.amount;
    this.#settlements = [...draft.settlements];
  }

  static create(draft: NettingDraft): IResult<Netting> {
    if (draft.by === draft.with) return Result.fail(new NettingWithSelfException());
    if (!(CURRENCIES as readonly string[]).includes(draft.currency)) {
      return Result.fail(new UnsupportedNettingCurrencyException());
    }
    if (!Number.isInteger(draft.amount) || draft.amount < 1 || draft.settlements.length === 0) {
      return Result.fail(new NothingToNetException());
    }
    const netting = new Netting(Id.generate(), draft);
    netting.record(
      NettingRecordedEvent.set({
        nettingId: netting.id,
        by: draft.by,
        with: draft.with,
        currency: draft.currency,
        amount: draft.amount,
      }),
    );
    return Result.ok(netting);
  }

  get id(): string {
    return this._id.value;
  }

  get by(): string {
    return this.#by;
  }

  get with(): string {
    return this.#with;
  }

  get currency(): string {
    return this.#currency;
  }

  get amount(): number {
    return this.#amount;
  }

  /** The settlements the netting made, in the order they were made. */
  get settlements(): readonly string[] {
    return this.#settlements;
  }
}
