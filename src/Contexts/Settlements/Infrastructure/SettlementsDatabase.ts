import {
  PostgresDatabase,
  PostgresTables,
  databaseUrl,
} from '@Architecture/Infrastructure/DataSources/PostgresDatabase';

/**
 * The tables the Settlements context keeps its settlement books in, in the database at `DATABASE_URL`, under tables of its own, as
 * Ledger's are (ADR 5). Several servers may use the database: its writes take turns, and its reads see what is committed.
 */
export class SettlementsDatabase extends PostgresTables {
  constructor(urlOf: () => string = databaseUrl) {
    super(urlOf, setUp, backfill);
  }
}

/**
 * The tables of the settlements, made once (idempotent). A settlement a file holds before its history was kept has no line of it: `backfill`
 * gives it the one it was recorded with, the only status Tally knows the time of (cash is recorded paid; through the provider, pending). Its
 * later statuses are not known, and are not made up.
 */
export async function setUp(database: PostgresDatabase): Promise<void> {
  await database.query(`
    CREATE TABLE IF NOT EXISTS settlement_books (
      id TEXT PRIMARY KEY,
      group_id TEXT NOT NULL UNIQUE,
      version INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS settlements (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY,
      id TEXT PRIMARY KEY,
      group_id TEXT NOT NULL,
      payer TEXT NOT NULL,
      payee TEXT NOT NULL,
      amount INTEGER NOT NULL,
      method TEXT NOT NULL,
      status TEXT NOT NULL,
      at TEXT NOT NULL,
      provider_payment_id TEXT,
      pay_url TEXT
    );
    CREATE INDEX IF NOT EXISTS settlements_by_group ON settlements (group_id);
    CREATE INDEX IF NOT EXISTS settlements_by_provider_payment ON settlements (provider_payment_id);
    CREATE TABLE IF NOT EXISTS settlement_history (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      settlement_id TEXT NOT NULL,
      status TEXT NOT NULL,
      at TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS settlement_history_by_settlement ON settlement_history (settlement_id);
    CREATE TABLE IF NOT EXISTS nettings (
      id TEXT PRIMARY KEY,
      asked_by TEXT NOT NULL,
      asked_with TEXT NOT NULL,
      currency TEXT NOT NULL,
      amount INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS netting_settlements (
      seq INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      netting_id TEXT NOT NULL,
      settlement_id TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS netting_settlements_by_netting ON netting_settlements (netting_id);
    CREATE INDEX IF NOT EXISTS netting_settlements_by_settlement ON netting_settlements (settlement_id);
    CREATE TABLE IF NOT EXISTS payout_accounts (
      id TEXT PRIMARY KEY,
      owner_id TEXT NOT NULL UNIQUE,
      account_id TEXT NOT NULL,
      version INTEGER NOT NULL
    );
  `);
}

/** The history a settlement a file holds has no line of (see `setUp`): DML only, once the file's rows are in. */
export async function backfill(database: PostgresDatabase): Promise<void> {
  await database.query(`
    INSERT INTO settlement_history (settlement_id, status, at)
    SELECT id, CASE WHEN method IN ('cash', 'net') THEN 'paid' ELSE 'pending' END, at FROM settlements
    WHERE id NOT IN (SELECT settlement_id FROM settlement_history);
  `);
}
