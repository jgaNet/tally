import { ConcurrencyConflictException } from '@Architecture/Domain';
import { PostgresDatabase } from '@Architecture/Infrastructure/Postgres/PostgresDatabase';

import {
  ISettlementStore,
  SettlementStatusEntry,
  SettlementView,
} from '@Contexts/Settlements/Application/ISettlementStore';
import { WaitingPayment, SettlementBook } from '@Contexts/Settlements/Domain/Settlement/SettlementBook';
import { Settlement, SettlementMethod, SettlementStatus } from '@Contexts/Settlements/Domain/Settlement/Settlement';

/**
 * The settlements' tables (features 12 and 13, ADR 10). `settlement_books` is the version each group's book is at: one row per group
 * with a settlement, written with the first one and bumped with each change after it, only while the book is still at the version it
 * was read at. `settlements` is one row per settlement, in cash or through the provider (`method`), kept as it was decided, and its
 * `status` (`pending` while the provider has not said, `paid`, `failed`, and for a refund `refunding` and `refunded`) is the one thing that
 * changes after it is decided; a
 * provider's payment keeps the provider's id (`payment_id`, the webhook names it) and the link the payer pays at (`pay_url`). The
 * balances read the paid ones through `PostgresSettlementRoster`, so a settlement is counted once it is paid. The group is a group of
 * Groups: the foreign key only names its id, as Ledger's does. `settlement_history` is one line per status a settlement has had, with
 * when Tally learned it (request 19), written with the status in the same transaction.
 */
export const settlementsTablesSchema = [
  `CREATE TABLE IF NOT EXISTS settlement_books (
     group_id TEXT PRIMARY KEY REFERENCES groups(id),
     version INTEGER NOT NULL
   )`,
  `CREATE TABLE IF NOT EXISTS settlements (
     id TEXT PRIMARY KEY,
     group_id TEXT NOT NULL REFERENCES groups(id),
     payer_id TEXT NOT NULL,
     payee_id TEXT NOT NULL,
     amount INTEGER NOT NULL,
     method TEXT NOT NULL CHECK (method IN ('cash', 'provider')),
     status TEXT NOT NULL CHECK (status IN ('pending', 'paid', 'failed', 'refunding', 'refunded')),
     recorded_at TEXT NOT NULL,
     payment_id TEXT UNIQUE,
     pay_url TEXT,
     rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,
     CHECK (method = 'cash' OR (payment_id IS NOT NULL AND pay_url IS NOT NULL))
   )`,
  `CREATE TABLE IF NOT EXISTS settlement_history (
     seq INTEGER PRIMARY KEY AUTOINCREMENT,
     settlement_id TEXT NOT NULL REFERENCES settlements(id),
     status TEXT NOT NULL CHECK (status IN ('pending', 'paid', 'failed', 'refunding', 'refunded')),
     learned_at TEXT NOT NULL
   )`,
  'CREATE INDEX IF NOT EXISTS settlements_by_group ON settlements (group_id)',
  'CREATE INDEX IF NOT EXISTS settlement_history_by_settlement ON settlement_history (settlement_id)',
];

/**
 * The history of a settlement (request 19): one line per status it has had, written in the transaction of the status's fact, so a
 * webhook that changes nothing writes nothing. `seq` keeps them in the order they were learned.
 */
interface HistoryRow {
  settlement_id: string;
  status: SettlementStatus;
  learned_at: string;
}

interface SettlementRow {
  id: string;
  group_id: string;
  payer_id: string;
  payee_id: string;
  amount: number;
  method: SettlementMethod;
  status: SettlementStatus;
  recorded_at: string;
  payment_id: string | null;
  pay_url: string | null;
}

/** A settlement row as the domain keeps it. */
const toSettlement = (row: SettlementRow): Settlement => ({
  id: row.id,
  groupId: row.group_id,
  from: row.payer_id,
  to: row.payee_id,
  amount: row.amount,
  method: row.method,
  status: row.status,
  at: row.recorded_at,
  ...(row.payment_id !== null && row.pay_url !== null && { payment: { id: row.payment_id, payUrl: row.pay_url } }),
});

/** What a screen shows of a settlement: its history (request 19), and the link the payer pays at, through the provider only. */
const toView = (settlement: Settlement, history: SettlementStatusEntry[]): SettlementView => ({
  id: settlement.id,
  groupId: settlement.groupId,
  from: settlement.from,
  to: settlement.to,
  amount: settlement.amount,
  method: settlement.method,
  status: settlement.status,
  at: settlement.at,
  history,
  ...(settlement.payment && { payUrl: settlement.payment.payUrl }),
});

const toEntry = (row: HistoryRow): SettlementStatusEntry => ({ status: row.status, at: row.learned_at });

/**
 * The settlements in PostgreSQL. `save` checks the group's book is still at the version it was read at, and stores the next one with the
 * settlement (or its new status), in the command's transaction; it refuses a book another writer moved on with a
 * ConcurrencyConflictException (CONC-OPTIMISTIC). `versionOf`, `waitingOf`, `settlementOfPayment`, `settlementOf` and `viewOf` read the
 * committed data.
 */
export class PostgresSettlementStore implements ISettlementStore {
  constructor(private readonly database: PostgresDatabase) {}

  async versionOf(groupId: string): Promise<number> {
    const row = (await this.database.read(db =>
      db.prepare('SELECT version FROM settlement_books WHERE group_id = ?').get(groupId),
    )) as { version: number } | undefined;
    return row?.version ?? 0;
  }

  async waitingOf(groupId: string): Promise<WaitingPayment[]> {
    const rows = (await this.database.read(db =>
      db
        .prepare("SELECT payer_id, payee_id, amount FROM settlements WHERE group_id = ? AND status = 'pending'")
        .all(groupId),
    )) as { payer_id: string; payee_id: string; amount: number }[];
    return rows.map(row => ({ from: row.payer_id, to: row.payee_id, amount: row.amount }));
  }

  async save(book: SettlementBook, settlement: Settlement, learnedAt: string): Promise<void> {
    await this.#checkVersion(book);
    const writer = this.database.writer;
    await writer
      .prepare(
        `INSERT INTO settlements (id, group_id, payer_id, payee_id, amount, method, status, recorded_at, payment_id, pay_url)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
         ON CONFLICT (id) DO UPDATE SET status = excluded.status`,
      )
      .run(
        settlement.id,
        settlement.groupId,
        settlement.from,
        settlement.to,
        settlement.amount,
        settlement.method,
        settlement.status,
        settlement.at,
        settlement.payment?.id ?? null,
        settlement.payment?.payUrl ?? null,
      );
    await writer
      .prepare('INSERT INTO settlement_history (settlement_id, status, learned_at) VALUES (?, ?, ?)')
      .run(settlement.id, settlement.status, learnedAt);
  }

  async viewOf(settlementId: string): Promise<SettlementView | undefined> {
    const row = (await this.database.read(db =>
      db.prepare('SELECT * FROM settlements WHERE id = ?').get(settlementId),
    )) as SettlementRow | undefined;
    if (!row) return undefined;
    const history = (await this.database.read(db =>
      db
        .prepare(
          'SELECT settlement_id, status, learned_at FROM settlement_history WHERE settlement_id = ? ORDER BY seq',
        )
        .all(settlementId),
    )) as unknown as HistoryRow[];
    return toView(toSettlement(row), history.map(toEntry));
  }

  async viewsOfGroup(groupId: string): Promise<SettlementView[]> {
    const rows = (await this.database.read(db =>
      db.prepare('SELECT * FROM settlements WHERE group_id = ? ORDER BY recorded_at DESC, rowid DESC').all(groupId),
    )) as unknown as SettlementRow[];
    const history = (await this.database.read(db =>
      db
        .prepare(
          `SELECT h.settlement_id, h.status, h.learned_at FROM settlement_history h
           JOIN settlements s ON s.id = h.settlement_id WHERE s.group_id = ? ORDER BY h.seq`,
        )
        .all(groupId),
    )) as unknown as HistoryRow[];
    const byId = new Map<string, SettlementStatusEntry[]>();
    for (const line of history) byId.set(line.settlement_id, [...(byId.get(line.settlement_id) ?? []), toEntry(line)]);
    return rows.map(row => toView(toSettlement(row), byId.get(row.id) ?? []));
  }

  async settlementOf(settlementId: string): Promise<Settlement | undefined> {
    const row = (await this.database.read(db =>
      db.prepare('SELECT * FROM settlements WHERE id = ?').get(settlementId),
    )) as SettlementRow | undefined;
    return row ? toSettlement(row) : undefined;
  }

  async settlementOfPayment(paymentId: string): Promise<Settlement | undefined> {
    const row = (await this.database.read(db =>
      db.prepare('SELECT * FROM settlements WHERE payment_id = ?').get(paymentId),
    )) as SettlementRow | undefined;
    return row ? toSettlement(row) : undefined;
  }

  /** Stores the book at its version + 1, only if it is still at the version it was read at; the first settlement creates the row. */
  async #checkVersion(book: SettlementBook): Promise<void> {
    const writer = this.database.writer;
    const { changes } = await (book.version === 0
      ? writer
          .prepare('INSERT INTO settlement_books (group_id, version) VALUES (?, 1) ON CONFLICT DO NOTHING')
          .run(book.groupId)
      : writer
          .prepare('UPDATE settlement_books SET version = ? WHERE group_id = ? AND version = ?')
          .run(book.version + 1, book.groupId, book.version));
    if (changes === 0) {
      throw new ConcurrencyConflictException(
        'Settlements',
        'The settlements of the group changed since they were read: read them again',
      );
    }
  }
}
