// PostgreSQL sends BIGINT (sums, counts) and NUMERIC as text. Every number Tally keeps or sums is a safe integer.
types.setTypeParser(types.builtins.INT8, value => Number(value));
types.setTypeParser(types.builtins.NUMERIC, value => Number(value));

/** The lock every write transaction holds: one writer at a time, on every server sharing the database. */
