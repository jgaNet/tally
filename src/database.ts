/** The database: every read and write Tally makes goes through it, to the PostgreSQL database it was opened on. */
export class Database {
  constructor(private readonly pool: Pool) {
    pool.on('error', () => {
      // An idle connection that failed is dropped by the pool; the next query gets another one.
    });
  }

  /** Every row `sql` answers with `params` (`?` for each, in order). */
  async rows<Row = Record<string, unknown>>(sql: string, params: readonly unknown[] = []): Promise<Row[]> {
    return (await this.run(sql, params)).rows as Row[];
  }

  /** The first row `sql` answers, or `undefined` when it answers none. */
  async row<Row = Record<string, unknown>>(sql: string, params: readonly unknown[] = []): Promise<Row | undefined> {
    return (await this.rows<Row>(sql, params))[0];
  }

  /** Runs `sql`, and answers how many rows it changed. */
  async execute(sql: string, params: readonly unknown[] = []): Promise<number> {
    return (await this.run(sql, params)).rowCount ?? 0;
  }

  /** Runs `work` in a transaction of its own, or joins the one of this database it is already in. */
  async transaction<T>(work: () => Promise<T>): Promise<T> {
    if (transactions.getStore()?.owner === this) {
      return work();
    }
    const client = await this.pool.connect();
    let broken = false;
    try {
      await client.query('BEGIN');
      await client.query('SELECT pg_advisory_xact_lock($1)', [WRITE_LOCK]);
      const result = await transactions.run({ owner: this, client }, work);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      try {
        await client.query('ROLLBACK');
      } catch {
        broken = true;
      }
      throw error;
    } finally {
      client.release(broken);
    }
  }

  /** Closes the connections. */
  async close(): Promise<void> {
    await this.pool.end();
  }

  private run(sql: string, params: readonly unknown[]) {
    const transaction = transactions.getStore();
    const queryable = transaction?.owner === this ? transaction.client : this.pool;
    return queryable.query(toPositional(sql), [...params]);
  }
}

/** The transaction a call is made in, if any: the connection it runs on, and the database it is for. */
const transactions = new AsyncLocalStorage<{ owner: Database; client: PoolClient }>();

/** Runs `work` under the write lock of `db`: its writes all land, or none does. */
export function inTransaction<T>(db: Database, work: () => Promise<T>): Promise<T> {
  return db.transaction(work);
}

/** `?` placeholders, as the queries are written, to the `$1, $2, …` PostgreSQL takes. A `?` inside a string is left alone. */
export function toPositional(sql: string): string {
  let position = 0;
  let quoted = false;
  let out = '';
  for (const character of sql) {
    if (character === "'") {
      quoted = !quoted;
    }
    if (character === '?' && !quoted) {
      position += 1;
      out += `$${position}`;
    } else {
      out += character;
    }
  }
  return out;
}

/** The tables that hold Tally's data: a database with a row in any of them is not empty. */
const DATA_TABLES = IMPORTED_TABLES.map(table => table.name);

/**
 * Opens the PostgreSQL database at `url` and brings its schema up to date. When `legacyFile` names a file Tally kept
 * as SQLite and the database holds nothing of Tally's, what the file holds is moved into the database first, in the
 * same transaction; from then on the file is not read. Several servers may start on one database at once: the
 * steps run under the write lock, and each server looks at the database once it holds it.
 */
export async function openDatabase(url: string, legacyFile?: string): Promise<Database> {
  const pool = new Pool({ connectionString: url, max: 10 });
  const db = new Database(pool);
  try {
    await prepare(pool, legacyFile);
  } catch (error) {
    // Only once the connection that prepared it is back in the pool: a pool does not end while one is out.
    await pool.end();
    throw error;
  }
  return db;
}

/** Brings the database up to date, and moves the legacy file in, in one transaction. */
async function prepare(pool: Pool, legacyFile: string | undefined): Promise<void> {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock($1)', [WRITE_LOCK]);
    await migrate(client);
    if (
      legacyFile !== undefined &&
      existsSync(legacyFile) &&
      !(await isImported(client)) &&
      !(await holdsData(client))
    ) {
      await importLegacyFile(client, legacyFile);
    }
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK').catch(() => undefined);
    throw error;
  } finally {
    client.release();
  }
}

async function migrate(client: PoolClient): Promise<void> {
  await client.query(
    'CREATE TABLE IF NOT EXISTS tally_schema (id INTEGER PRIMARY KEY CHECK (id = 1), version INTEGER NOT NULL)',
  );
  const current = (await client.query('SELECT version FROM tally_schema')).rows[0]?.version ?? 0;
  for (let step = current; step < migrations.length; step++) {
    await client.query(migrations[step]);
  }
  if (current < migrations.length) {
    await client.query(
      `INSERT INTO tally_schema (id, version) VALUES (1, $1)
       ON CONFLICT (id) DO UPDATE SET version = excluded.version`,
      [migrations.length],
    );
  }
}

async function isImported(client: PoolClient): Promise<boolean> {
  return (await client.query('SELECT 1 FROM legacy_import')).rowCount !== 0;
}

async function holdsData(client: PoolClient): Promise<boolean> {
  const checks = DATA_TABLES.map(table => `EXISTS (SELECT 1 FROM ${table})`).join(' OR ');
  return (await client.query(`SELECT ${checks} AS held`)).rows[0].held === true;
}
