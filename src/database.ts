import { existsSync } from 'node:fs';
import pg from 'pg';
import { CATEGORY_SQL_LIST } from './categories';
import { readLegacyFile, type LegacyTable } from './legacy-file';

/** The result of a statement: how many rows it changed. */
export interface RunResult {
  readonly changes: number;
}

/** A statement, with its parameters given in order, one for each `?` of its text. */
export interface Statement {
  run(...params: unknown[]): Promise<RunResult>;
  get<T = Record<string, unknown>>(...params: unknown[]): Promise<T | undefined>;
  all<T = Record<string, unknown>>(...params: unknown[]): Promise<T[]>;
}

/** What statements run on: the database, or one connection of it in a transaction. */
export interface Querier {
  prepare(text: string): Statement;
  /** Statements without parameters, run one after another. */
  exec(text: string): Promise<void>;
}

/** The database of the application. Queries run on any connection; a transaction takes one of its own. */
export interface Database extends Querier {
  /** Runs `work` on one connection, which is given back to the pool when it ends. */
  withConnection<T>(work: (connection: Querier) => Promise<T>): Promise<T>;
  close(): Promise<void>;
}

/**
 * The advisory lock every write takes once its transaction has begun, and the schema is created under. Writes of all
 * servers sharing the database run one after another, as they did on a file, so each read-then-write is one step.
 */
export const WRITE_LOCK = 7300130;

/** How many connections a server keeps to the database. */
const POOL_SIZE = 10;

/** `bigint` (`COUNT`) and `numeric` (`SUM`) columns come back as numbers: every amount and count fits in a safe integer. */
const INT8_OID = 20;
const NUMERIC_OID = 1700;
const types = {
  getTypeParser: (oid: number, format?: 'text' | 'binary') =>
    oid === INT8_OID || oid === NUMERIC_OID ? (value: string) => Number(value) : pg.types.getTypeParser(oid, format),
};

/**
 * The schema, created when missing. Every table is created with `IF NOT EXISTS`. A table whose rows are read in the
 * order they were written has a `seq`, an identity column that counts them (what SQLite's `rowid` was).
 */
const SCHEMA = `
  CREATE TABLE IF NOT EXISTS accounts (
    id            TEXT PRIMARY KEY,
    email         TEXT NOT NULL,
    email_key     TEXT NOT NULL UNIQUE,
    name          TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at    TEXT NOT NULL
  );
  /*
   * An account deleted by its person keeps its id, which the groups, expenses, settlements and logs refer to: its name is
   * then \`Deleted account\`, its email is erased (its email_key is its id, so the email is free), and \`deleted_at\` says when.
   * A deleted account signs in and is found by nothing, as if no account had its email.
   */
  ALTER TABLE accounts ADD COLUMN IF NOT EXISTS deleted_at TEXT;
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    account_id TEXT NOT NULL REFERENCES accounts (id),
    created_at TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS operations (
    id            TEXT PRIMARY KEY,
    status        TEXT NOT NULL CHECK (status IN ('PENDING', 'SUCCESS', 'ERROR')),
    result        TEXT,
    error_type    TEXT,
    error_message TEXT,
    account_id    TEXT REFERENCES accounts (id),
    created_at    TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS groups (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          TEXT PRIMARY KEY,
    name        TEXT NOT NULL,
    currency    TEXT NOT NULL CHECK (currency IN ('EUR', 'USD', 'GBP', 'CHF', 'CAD', 'AUD')),
    owner_id    TEXT NOT NULL REFERENCES accounts (id),
    created_at  TEXT NOT NULL,
    archived_at TEXT
  );
  CREATE TABLE IF NOT EXISTS group_members (
    seq          BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    group_id     TEXT NOT NULL REFERENCES groups (id),
    account_id   TEXT NOT NULL REFERENCES accounts (id),
    joined_at    TEXT NOT NULL,
    left_at      TEXT,
    balance_base BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (group_id, account_id)
  );
  CREATE INDEX IF NOT EXISTS group_members_by_account ON group_members (account_id);
  CREATE TABLE IF NOT EXISTS invitations (
    id         TEXT PRIMARY KEY,
    group_id   TEXT NOT NULL REFERENCES groups (id),
    created_by TEXT NOT NULL REFERENCES accounts (id),
    created_at TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS expenses (
    seq               BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id                TEXT PRIMARY KEY,
    group_id          TEXT NOT NULL REFERENCES groups (id),
    description       TEXT NOT NULL,
    amount            BIGINT NOT NULL,
    spent_on          TEXT NOT NULL,
    paid_by           TEXT NOT NULL REFERENCES accounts (id),
    version           BIGINT NOT NULL DEFAULT 1,
    split_kind        TEXT NOT NULL DEFAULT 'equal' CHECK (split_kind IN ('equal', 'exact', 'shares')),
    original_currency TEXT,
    original_amount   BIGINT,
    rate              TEXT,
    recurring_id      TEXT,
    recurring_day     TEXT,
    category          TEXT NOT NULL DEFAULT 'other' CHECK (category IN (${CATEGORY_SQL_LIST})),
    created_at        TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS expense_shares (
    expense_id TEXT NOT NULL REFERENCES expenses (id),
    position   BIGINT NOT NULL,
    member_id  TEXT NOT NULL REFERENCES accounts (id),
    amount     BIGINT NOT NULL,
    PRIMARY KEY (expense_id, position)
  );
  /*
   * A recurring expense, with its split as given (one row per member in recurring_parts: the amount of an exact
   * split, the shares of a split by shares, nothing for an equal one). next_on is the day of the next expense to
   * record; it moves in the transaction that records the expense.
   */
  CREATE TABLE IF NOT EXISTS recurring (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          TEXT PRIMARY KEY,
    group_id    TEXT NOT NULL REFERENCES groups (id),
    paid_by     TEXT NOT NULL REFERENCES accounts (id),
    description TEXT NOT NULL,
    amount      BIGINT NOT NULL,
    starts_on   TEXT NOT NULL,
    next_on     TEXT NOT NULL,
    split_kind  TEXT NOT NULL CHECK (split_kind IN ('equal', 'exact', 'shares')),
    category    TEXT NOT NULL DEFAULT 'other' CHECK (category IN (${CATEGORY_SQL_LIST})),
    created_at  TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS recurring_parts (
    recurring_id TEXT NOT NULL REFERENCES recurring (id),
    position     BIGINT NOT NULL,
    member_id    TEXT NOT NULL REFERENCES accounts (id),
    value        BIGINT,
    PRIMARY KEY (recurring_id, position)
  );
  CREATE TABLE IF NOT EXISTS payout_accounts (
    account_id          TEXT PRIMARY KEY REFERENCES accounts (id),
    provider_account_id TEXT NOT NULL,
    set_at              TEXT NOT NULL
  );
  /*
   * The debts the background job watches: a member it saw owing more than the reminder threshold in a group,
   * since noted_at, and when it last reminded them. A member seen owing less is no longer watched.
   */
  CREATE TABLE IF NOT EXISTS lasting_debts (
    group_id         TEXT NOT NULL REFERENCES groups (id),
    account_id       TEXT NOT NULL REFERENCES accounts (id),
    noted_at         TEXT NOT NULL,
    last_reminded_at TEXT,
    PRIMARY KEY (group_id, account_id)
  );
  /* The monthly budget of a category of a group. */
  CREATE TABLE IF NOT EXISTS budgets (
    group_id TEXT NOT NULL REFERENCES groups (id),
    category TEXT NOT NULL CHECK (category IN (${CATEGORY_SQL_LIST})),
    amount   BIGINT NOT NULL CHECK (amount BETWEEN 1 AND 100000000),
    PRIMARY KEY (group_id, category)
  );
  /*
   * The months of a category of a group whose budget has been noticed as passed: a row once, ever, written in the
   * transaction that makes the notices, so each month is noticed once.
   */
  CREATE TABLE IF NOT EXISTS budget_months_passed (
    group_id  TEXT NOT NULL REFERENCES groups (id),
    category  TEXT NOT NULL CHECK (category IN (${CATEGORY_SQL_LIST})),
    month     TEXT NOT NULL,
    passed_at TEXT NOT NULL,
    PRIMARY KEY (group_id, category, month)
  );
  /*
   * A split saved under a name in a group, by a member. Its name is unique in the group whatever its case (name_key).
   * Its parts (one row per member in template_parts: the shares of a split by shares, nothing for an equal one).
   */
  CREATE TABLE IF NOT EXISTS templates (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          TEXT PRIMARY KEY,
    group_id    TEXT NOT NULL REFERENCES groups (id),
    saved_by    TEXT NOT NULL REFERENCES accounts (id),
    name        TEXT NOT NULL,
    name_key    TEXT NOT NULL,
    split_kind  TEXT NOT NULL CHECK (split_kind IN ('equal', 'shares')),
    created_at  TEXT NOT NULL,
    UNIQUE (group_id, name_key)
  );
  CREATE TABLE IF NOT EXISTS template_parts (
    template_id TEXT NOT NULL REFERENCES templates (id),
    position    BIGINT NOT NULL,
    member_id   TEXT NOT NULL REFERENCES accounts (id),
    shares      BIGINT CHECK (shares IS NULL OR shares >= 1),
    PRIMARY KEY (template_id, position)
  );
  /*
   * A notice to a member. One about an expense is written in the transaction that records the expense, so it exists
   * exactly when the expense does; it names the expense without a foreign key: deleting the expense keeps it. One
   * per expense and recipient, whatever happens to the server. A reminder (of a lasting debt) has no expense. A budget's
   * notice names its category, its month (\`YYYY-MM\`), the budget and what the month spends (its \`amount\`).
   * \`group_id\` has no foreign key: a group merged into another is gone, and its notices stay as they were made.
   */
  CREATE TABLE IF NOT EXISTS notices (
    seq          BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id           TEXT PRIMARY KEY,
    recipient_id TEXT NOT NULL REFERENCES accounts (id),
    kind         TEXT NOT NULL CHECK (kind IN ('expense', 'reminder', 'budget')),
    group_id     TEXT NOT NULL,
    expense_id   TEXT,
    category     TEXT CHECK (category IN (${CATEGORY_SQL_LIST})),
    month        TEXT,
    budget       BIGINT,
    amount       BIGINT NOT NULL,
    created_at   TEXT NOT NULL,
    CHECK ((kind = 'expense') = (expense_id IS NOT NULL)),
    CHECK ((kind = 'budget') = (budget IS NOT NULL AND month IS NOT NULL AND category IS NOT NULL)),
    UNIQUE (kind, expense_id, recipient_id)
  );
  /*
   * The audit of a group: every change of money, one row per change, written in the transaction that makes the change, so
   * it exists exactly when the change does. Nothing changes or removes a row, and no row refers to what it is about (an
   * expense deleted, or a member who left, keeps its entries). \`subject_id\` is what the change is about, \`by_id\` who made it.
   */
  CREATE TABLE IF NOT EXISTS audit_entries (
    seq        BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id         TEXT PRIMARY KEY,
    group_id   TEXT NOT NULL REFERENCES groups (id),
    at         TEXT NOT NULL,
    by_id      TEXT NOT NULL REFERENCES accounts (id),
    action     TEXT NOT NULL CHECK (action IN ('expense-recorded', 'expense-edited', 'expense-deleted',
                 'settlement-paid', 'settlement-refunded', 'settlement-contested', 'balance-passed')),
    subject_id TEXT NOT NULL,
    amount     BIGINT NOT NULL
  );
  /*
   * The administrators' log: every decision an administrator makes about a contested settlement, and every suspension and
   * reinstatement of an account, one row per change, written in the transaction that makes it. Nothing changes or removes
   * a row. \`by_id\` is the administrator who decided or changed it.
   */
  CREATE TABLE IF NOT EXISTS admin_log (
    seq        BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id         TEXT PRIMARY KEY,
    at         TEXT NOT NULL,
    by_id      TEXT NOT NULL REFERENCES accounts (id),
    action     TEXT NOT NULL CHECK (action IN ('decided-paid', 'decided-annulled', 'suspended', 'reinstated')),
    subject_id TEXT NOT NULL
  );
  /*
   * The accounts suspended by an administrator: a row while an account is suspended, removed when it is reinstated. A
   * suspension changes nothing else; what a suspended account cannot do is refused where each change is made.
   */
  CREATE TABLE IF NOT EXISTS suspensions (
    account_id   TEXT PRIMARY KEY REFERENCES accounts (id),
    suspended_at TEXT NOT NULL
  );
  /*
   * The receipt of an expense: the id and the link the receipts store gave its file, and its type and size. One per
   * expense: a receipt attached replaces the one it had. It is written in the transaction that attaches it, and deleted
   * with its expense. Tally keeps no file, only what the store answered.
   */
  CREATE TABLE IF NOT EXISTS receipts (
    expense_id  TEXT PRIMARY KEY REFERENCES expenses (id),
    store_id    TEXT NOT NULL,
    type        TEXT NOT NULL CHECK (type IN ('image/jpeg', 'image/png')),
    size        BIGINT NOT NULL CHECK (size BETWEEN 1 AND 2097152),
    url         TEXT NOT NULL,
    attached_at TEXT NOT NULL
  );
  /*
   * The settlements table. A settlement in cash is \`paid\` at once; one through the payment provider is \`pending\`
   * with the provider's payment id and \`payUrl\`, until the provider says it \`paid\` or \`failed\`. A paid one may be
   * \`refunding\` (asked of the provider) and then \`refunded\`, as the provider says. A settlement by netting is \`paid\`
   * at once, as one in cash, and never refunded. A provider settlement that is \`paid\` may be \`contested\` by its payee, and
   * then is \`paid\` again or \`annulled\`, as an administrator decides.
   */
  CREATE TABLE IF NOT EXISTS settlements (
    seq                 BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id                  TEXT PRIMARY KEY,
    group_id            TEXT NOT NULL REFERENCES groups (id),
    payer_id            TEXT NOT NULL REFERENCES accounts (id),
    payee_id            TEXT NOT NULL REFERENCES accounts (id),
    amount              BIGINT NOT NULL CHECK (amount >= 1),
    method              TEXT NOT NULL,
    status              TEXT NOT NULL CHECK (status IN ('pending', 'paid', 'failed', 'refunding', 'refunded', 'contested', 'annulled')),
    provider_payment_id TEXT,
    pay_url             TEXT,
    created_at          TEXT NOT NULL,
    CONSTRAINT settlements_method_known CHECK (method IN ('cash', 'provider', 'net')),
    CONSTRAINT settlements_not_provider CHECK (method = 'provider' OR (status = 'paid' AND provider_payment_id IS NULL AND pay_url IS NULL)),
    CONSTRAINT settlements_provider CHECK (method <> 'provider' OR (provider_payment_id IS NOT NULL AND pay_url IS NOT NULL))
  );
  /*
   * A database created before settlements by netting kept the constraints of the methods cash and provider only: they are
   * replaced once, by the constraints named above (a database created now has them already).
   */
  DO $$
  BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'settlements_method_known' AND conrelid = 'settlements'::regclass) THEN
      ALTER TABLE settlements DROP CONSTRAINT IF EXISTS settlements_method_check;
      ALTER TABLE settlements DROP CONSTRAINT IF EXISTS settlements_check;
      ALTER TABLE settlements DROP CONSTRAINT IF EXISTS settlements_check1;
      ALTER TABLE settlements ADD CONSTRAINT settlements_method_known CHECK (method IN ('cash', 'provider', 'net'));
      ALTER TABLE settlements ADD CONSTRAINT settlements_not_provider CHECK (method = 'provider' OR (status = 'paid' AND provider_payment_id IS NULL AND pay_url IS NULL));
      ALTER TABLE settlements ADD CONSTRAINT settlements_provider CHECK (method <> 'provider' OR (provider_payment_id IS NOT NULL AND pay_url IS NOT NULL));
    END IF;
  END $$;
  /*
   * A netting: what two members owe each other in a currency, netted across the groups they share, as settlements the
   * balances count at once. \`by_id\` asked, \`with_id\` is the other member. Its settlements are in \`netting_settlements\`,
   * in the order they were made. Both are written in the transaction that makes the settlements.
   */
  CREATE TABLE IF NOT EXISTS nettings (
    seq        BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id         TEXT PRIMARY KEY,
    by_id      TEXT NOT NULL REFERENCES accounts (id),
    with_id    TEXT NOT NULL REFERENCES accounts (id),
    currency   TEXT NOT NULL CHECK (currency IN ('EUR', 'USD', 'GBP', 'CHF', 'CAD', 'AUD')),
    amount     BIGINT NOT NULL CHECK (amount >= 1),
    created_at TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS netting_settlements (
    netting_id    TEXT NOT NULL REFERENCES nettings (id),
    position      BIGINT NOT NULL,
    settlement_id TEXT NOT NULL REFERENCES settlements (id),
    PRIMARY KEY (netting_id, position)
  );
  /*
   * Every status a settlement has had, one row per change, in the order they were learned (the \`seq\` order). A row is
   * written in the transaction that changes the settlement, so the history exists exactly when the change does.
   */
  CREATE TABLE IF NOT EXISTS settlement_statuses (
    seq           BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    settlement_id TEXT NOT NULL REFERENCES settlements (id),
    status        TEXT NOT NULL CHECK (status IN ('pending', 'paid', 'failed', 'refunding', 'refunded', 'contested', 'annulled')),
    at            TEXT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS settlement_statuses_by_settlement ON settlement_statuses (settlement_id);
  CREATE INDEX IF NOT EXISTS settlements_by_payment ON settlements (provider_payment_id);
  CREATE INDEX IF NOT EXISTS audit_entries_by_group ON audit_entries (group_id, at);
  /*
   * A database created before contested settlements kept the CHECKs of the statuses and actions named above without them:
   * each is replaced once, by the one named here (a database created now has it already).
   */
  DO $$
  BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'settlements_status_check' AND conrelid = 'settlements'::regclass AND pg_get_constraintdef(oid) LIKE '%annulled%') THEN
      ALTER TABLE settlements DROP CONSTRAINT IF EXISTS settlements_status_check;
      ALTER TABLE settlements ADD CONSTRAINT settlements_status_check CHECK (status IN ('pending', 'paid', 'failed', 'refunding', 'refunded', 'contested', 'annulled'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'settlement_statuses_status_check' AND conrelid = 'settlement_statuses'::regclass AND pg_get_constraintdef(oid) LIKE '%annulled%') THEN
      ALTER TABLE settlement_statuses DROP CONSTRAINT IF EXISTS settlement_statuses_status_check;
      ALTER TABLE settlement_statuses ADD CONSTRAINT settlement_statuses_status_check CHECK (status IN ('pending', 'paid', 'failed', 'refunding', 'refunded', 'contested', 'annulled'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'audit_entries_action_check' AND conrelid = 'audit_entries'::regclass AND pg_get_constraintdef(oid) LIKE '%settlement-contested%') THEN
      ALTER TABLE audit_entries DROP CONSTRAINT IF EXISTS audit_entries_action_check;
      ALTER TABLE audit_entries ADD CONSTRAINT audit_entries_action_check CHECK (action IN ('expense-recorded', 'expense-edited', 'expense-deleted',
        'settlement-paid', 'settlement-refunded', 'settlement-contested', 'balance-passed'));
    END IF;
  END $$;
  /* A database created before suspensions kept the CHECK of the administrators' log's actions without them: it is replaced once. */
  DO $$
  BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'admin_log_action_check' AND conrelid = 'admin_log'::regclass AND pg_get_constraintdef(oid) LIKE '%reinstated%') THEN
      ALTER TABLE admin_log DROP CONSTRAINT IF EXISTS admin_log_action_check;
      ALTER TABLE admin_log ADD CONSTRAINT admin_log_action_check CHECK (action IN ('decided-paid', 'decided-annulled', 'suspended', 'reinstated'));
    END IF;
  END $$;
  /* A database created before the merge of groups kept a foreign key on notices.group_id: it goes, as above. */
  ALTER TABLE notices DROP CONSTRAINT IF EXISTS notices_group_id_fkey;
  CREATE INDEX IF NOT EXISTS notices_by_recipient ON notices (recipient_id, created_at);
  /*
   * The notice preferences of a person: one row per kind of notice they turned off or on again. A kind with no row is on, so
   * every kind is on until its person turns it off. Written in a write transaction, which the notices made read it under.
   */
  CREATE TABLE IF NOT EXISTS notice_preferences (
    account_id TEXT NOT NULL REFERENCES accounts (id),
    kind       TEXT NOT NULL CHECK (kind IN ('expense', 'reminder', 'budget')),
    enabled    BOOLEAN NOT NULL,
    PRIMARY KEY (account_id, kind)
  );
  CREATE INDEX IF NOT EXISTS expenses_by_category ON expenses (group_id, category, spent_on);
  /* One expense per day of a recurring expense, whatever servers share the database. */
  CREATE UNIQUE INDEX IF NOT EXISTS expenses_by_recurring_day ON expenses (recurring_id, recurring_day)
    WHERE recurring_id IS NOT NULL;
`;

/** A parameter list of a statement has at most this many values (PostgreSQL's limit is 65535). */
const MAX_PARAMETERS = 30000;

/**
 * The text of a statement with each `?` (outside quotes) numbered as PostgreSQL wants it: `$1`, `$2`, and so on, in the
 * order of the parameters given.
 */
export function withNumberedParameters(text: string): string {
  let numbered = '';
  let count = 0;
  let quote: string | undefined;
  for (const character of text) {
    if (quote !== undefined) {
      if (character === quote) quote = undefined;
      numbered += character;
    } else if (character === "'" || character === '"') {
      quote = character;
      numbered += character;
    } else if (character === '?') {
      count += 1;
      numbered += `$${count}`;
    } else {
      numbered += character;
    }
  }
  return numbered;
}

class PgQuerier implements Querier {
  constructor(private readonly target: pg.Pool | pg.PoolClient) {}

  prepare(text: string): Statement {
    const sql = withNumberedParameters(text);
    const target = this.target;
    return {
      async run(...params: unknown[]): Promise<RunResult> {
        const result = await target.query(sql, params);
        return { changes: result.rowCount ?? 0 };
      },
      async get<T>(...params: unknown[]): Promise<T | undefined> {
        const result = await target.query(sql, params);
        return result.rows[0] as T | undefined;
      },
      async all<T>(...params: unknown[]): Promise<T[]> {
        const result = await target.query(sql, params);
        return result.rows as T[];
      },
    };
  }

  async exec(text: string): Promise<void> {
    await this.target.query(text);
  }
}

class PgDatabase implements Database {
  constructor(private readonly pool: pg.Pool) {}

  prepare(text: string): Statement {
    return new PgQuerier(this.pool).prepare(text);
  }

  exec(text: string): Promise<void> {
    return new PgQuerier(this.pool).exec(text);
  }

  async withConnection<T>(work: (connection: Querier) => Promise<T>): Promise<T> {
    const client = await this.pool.connect();
    try {
      return await work(new PgQuerier(client));
    } finally {
      client.release();
    }
  }

  async close(): Promise<void> {
    await this.pool.end();
  }
}

/** Copies the rows of each legacy table into the database, in the order they were written. */
async function copyRows(connection: Querier, tables: readonly LegacyTable[]): Promise<void> {
  for (const table of tables) {
    if (table.rows.length === 0) continue;
    const columns = Object.keys(table.rows[0]);
    const columnList = columns.map(column => `"${column}"`).join(', ');
    const perStatement = Math.max(1, Math.floor(MAX_PARAMETERS / columns.length));
    for (let start = 0; start < table.rows.length; start += perStatement) {
      const batch = table.rows.slice(start, start + perStatement);
      const placeholders = batch.map(() => `(${columns.map(() => '?').join(', ')})`).join(', ');
      const values = batch.flatMap(row => columns.map(column => row[column] ?? null));
      await connection.prepare(`INSERT INTO ${table.name} (${columnList}) VALUES ${placeholders}`).run(...values);
    }
  }
}

/**
 * Opens the database at `url`, creating its schema when missing. A database that holds nothing of Tally's yet and has
 * the file `legacyPath` names (a file Tally kept on SQLite) first takes every row of that file, in one transaction with
 * the schema, so a failure leaves the database empty and the next start tries again. The file is read only then.
 * Several servers may open the same database, in turn or together: the schema is created under the write lock.
 */
export async function openDatabase(options: { url: string; legacyPath?: string }): Promise<Database> {
  const pool = new pg.Pool({ connectionString: options.url, max: POOL_SIZE, types });
  // An idle connection the server closes (a restart, an administrator's command) is dropped by the pool, which opens
  // another when a query needs one: the error is not the application's to fail on.
  pool.on('error', () => undefined);
  const database = new PgDatabase(pool);
  try {
    await database.withConnection(async connection => {
      await connection.exec('BEGIN');
      try {
        await connection.exec(`SELECT pg_advisory_xact_lock(${WRITE_LOCK})`);
        const present = await connection
          .prepare(`SELECT to_regclass('accounts') IS NOT NULL AS present`)
          .get<{ present: boolean }>();
        const legacy =
          !present?.present && options.legacyPath !== undefined && existsSync(options.legacyPath)
            ? readLegacyFile(options.legacyPath)
            : undefined;
        await connection.exec(SCHEMA);
        if (legacy !== undefined) await copyRows(connection, legacy);
        await connection.exec('COMMIT');
      } catch (error) {
        await connection.exec('ROLLBACK');
        throw error;
      }
    });
  } catch (error) {
    await pool.end();
    throw error;
  }
  return database;
}

/**
 * True when `error` is PostgreSQL refusing a row that repeats a unique key (SQLSTATE 23505). Checked by shape: errors
 * from the driver do not always pass `instanceof Error`.
 */
export function isUniqueViolation(error: unknown): boolean {
  return typeof error === 'object' && error !== null && 'code' in error && error.code === '23505';
}
