import { v4 as uuidv4 } from 'uuid';

import { Event } from '@Architecture/Domain';
import { Outbox, OutboxEntry } from '@Architecture/Application';
import { PostgresDatabase } from '@Architecture/Infrastructure/DataSources/PostgresDatabase';

/** The table the outbox keeps its facts in (created by the bootstrap's storage set-up, see `OUTBOX_TABLE_SQL`). */
export const OUTBOX_TABLE_SQL = `
  CREATE TABLE IF NOT EXISTS outbox (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    payload TEXT NOT NULL
  );
`;

/**
 * The transactional outbox in PostgreSQL (ADR 24): a fact is a row, appended in the transaction of the state it describes, so a
 * fact committed with its state survives a server killed before it is published, and is relayed again by the next start. A
 * published fact's row is deleted. Insertion order is publication order (`seq`).
 */
export class PostgresOutbox implements Outbox {
  constructor(private readonly database: PostgresDatabase) {}

  async append(events: Event<unknown>[]): Promise<OutboxEntry[]> {
    const entries: OutboxEntry[] = [];
    for (const event of events) {
      const entry = { id: uuidv4(), event };
      await this.database.query('INSERT INTO outbox (id, name, payload) VALUES ($1, $2, $3)', [
        entry.id,
        event.name,
        JSON.stringify(event.payload ?? null),
      ]);
      entries.push(entry);
    }
    return entries;
  }

  async pending(): Promise<OutboxEntry[]> {
    const { rows } = await this.database.query<{ id: string; name: string; payload: string }>(
      'SELECT id, name, payload FROM outbox ORDER BY seq',
    );
    return rows.map(row => ({ id: row.id, event: new Event({ name: row.name, payload: JSON.parse(row.payload) }) }));
  }

  async markPublished(id: string): Promise<void> {
    await this.database.query('DELETE FROM outbox WHERE id = $1', [id]);
  }
}
