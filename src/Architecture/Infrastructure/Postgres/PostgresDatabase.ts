import pg from 'pg';

// A BIGINT and a NUMERIC (a SUM of them) are read as numbers, as the amounts, versions and counts the application keeps are far below 2^53.
pg.types.setTypeParser(20, value => Number(value));
pg.types.setTypeParser(1700, value => Number(value));

/** The key of the advisory lock every write transaction of every server takes first: one writer at a time, as the one file's lock was. */
const WRITE_LOCK = 7_300_001;

/** The key of the advisory lock that holds the preparation of an empty database, and the move of the file into it, to one server. */
const PREPARATION_LOCK = 7_300_002;

/**
 * What the building blocks keep in the database: the outbox (ADR 24), the inbox (ADR 12) and a few settings a server must
 * agree on with every other server on the database (ADR 2). A context adds its own tables to `open()`.
 */
const BUILDING_BLOCKS_SCHEMA = [
  `CREATE TABLE IF NOT EXISTS outbox (
     seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     id TEXT NOT NULL UNIQUE,
     name TEXT NOT NULL,
     payload TEXT NOT NULL
   )`,
  `CREATE TABLE IF NOT EXISTS inbox (
     subscription TEXT NOT NULL,
     message_id TEXT NOT NULL,
     PRIMARY KEY (subscription, message_id)
   )`,
  `CREATE TABLE IF NOT EXISTS settings (name TEXT PRIMARY KEY, value TEXT NOT NULL)`,
];

/** A statement's text is written with `?` for each parameter; PostgreSQL numbers them. A `?` inside a quoted literal is left alone. */
export function positional(sql: string): string {
  let count = 0;
  let quoted = false;
  let out = '';
  for (const char of sql) {
    if (char === "'") quoted = !quoted;
    out += char === '?' && !quoted ? `$${++count}` : char;
  }
  return out;
}

/** Whether an error is a second row for a key that is unique (PostgreSQL's 23505). */
export function isUniqueViolation(error: unknown): boolean {
  return typeof error === 'object' && error !== null && (error as { code?: unknown }).code === '23505';
}

export type Param = string | number | bigint | boolean | null | Buffer | Uint8Array | undefined;

/** A statement ready to run, on the connection that holds it. */
export interface Statement {
  get(...params: Param[]): Promise<unknown>;
  all(...params: Param[]): Promise<unknown[]>;
  run(...params: Param[]): Promise<{ changes: number }>;
}

/** What a store runs its statements on: the writer inside a transaction, or the readers outside one. */
export interface Queryable {
  prepare(sql: string): Statement;
}

interface Target {
  query(text: string, values?: unknown[]): Promise<pg.QueryResult>;
}

class Session implements Queryable {
  constructor(private readonly target: Target) {}

  prepare(sql: string): Statement {
    const text = positional(sql);
    const execute = (params: Param[]) =>
      this.target.query(
        text,
        params.map(param => (param === undefined ? null : param)),
      );
    return {
      get: async (...params) => (await execute(params)).rows[0],
      all: async (...params) => (await execute(params)).rows,
      run: async (...params) => ({ changes: (await execute(params)).rowCount ?? 0 }),
    };
  }
}

/**
 * The database a process shares, in PostgreSQL, which any number of servers may open (ADR 2, ADR 25).
 *
 * Two kinds of connection. The writer holds the transactions: `begin()` takes the process's write turn, opens the
 * transaction and takes the database's write lock (an advisory lock, held to the end of the transaction), so one
 * transaction at a time writes, here and in every other server on the database. The readers answer the reads that are
 * not part of a transaction: they see what is committed and are never blocked by a writer. Because the writer serves one
 * transaction at a time, its statements never interleave with another request's.
 *
 * A transaction's own uncommitted writes are visible to its writer only, so a use case reads before it writes (or
 * through the writer, passed in by its adapter).
 *
 * A write outside a transaction (`writeAlone()`) takes the same turn, so it never lands inside another request's
 * transaction. It must not be called from inside a transaction: the turn is not reentrant.
 */
export class PostgresDatabase {
  readonly #pool: pg.Pool;
  readonly #client: pg.Client;
  readonly #writer: Session;
  readonly #reader: Session;
  /** The tail of the queue of transactions: each waits for the one before it to leave the turn. */
  #queue: Promise<unknown> = Promise.resolve();
  /** The turn the open transaction holds, given back at its commit or rollback. */
  #leave: (() => void) | undefined;

  private constructor(url: string) {
    this.#pool = new pg.Pool({ connectionString: url, max: 8 });
    this.#pool.on('error', () => undefined);
    this.#client = new pg.Client({ connectionString: url });
    this.#client.on('error', () => undefined);
    this.#writer = new Session(this.#client);
    this.#reader = new Session(this.#pool);
  }

  /**
   * Opens the database at `url`, with the tables of `schema` beside the building blocks'. The preparation is one transaction under
   * one lock, so that a second server started at the same time waits and finds it done. `before` is run, in that transaction, on
   * a database that holds nothing of Tally's yet, after its tables are made and before it is served: it is where what an earlier
   * storage kept is moved in. The statements of `schema` are run again after it, for what they fill from what is there.
   */
  static async open(
    url: string,
    schema: readonly string[] = [],
    before?: (database: Queryable) => Promise<void>,
  ): Promise<PostgresDatabase> {
    const database = new PostgresDatabase(url);
    try {
      await database.#client.connect();
      await database.#prepare([...BUILDING_BLOCKS_SCHEMA, ...schema], before);
    } catch (error) {
      await database.close();
      throw error;
    }
    return database;
  }

  /** The committed data, now: a read that is not part of any transaction. */
  read<T>(query: (db: Queryable) => Promise<T>): Promise<T> {
    return query(this.#reader);
  }

  /** The writer, for the statements of the transaction that holds it (between `begin()` and its end). */
  get writer(): Queryable {
    return this.#writer;
  }

  /** A write of its own, outside any transaction, on the turn: other transactions wait for it. */
  async writeAlone<T>(write: (db: Queryable) => Promise<T>): Promise<T> {
    const leave = await this.#takeTurn();
    try {
      await this.#client.query('BEGIN');
      await this.#client.query('SELECT pg_advisory_xact_lock($1)', [WRITE_LOCK]);
      try {
        const result = await write(this.#writer);
        await this.#client.query('COMMIT');
        return result;
      } catch (error) {
        await this.#rollbackQuietly();
        throw error;
      }
    } finally {
      leave();
    }
  }

  /** Takes the turn, then opens the transaction on it. The turn is given back at `commit()` or `rollback()`. */
  async begin(): Promise<void> {
    const leave = await this.#takeTurn();
    try {
      await this.#client.query('BEGIN');
      await this.#client.query('SELECT pg_advisory_xact_lock($1)', [WRITE_LOCK]);
    } catch (error) {
      await this.#rollbackQuietly();
      leave();
      throw error;
    }
    this.#leave = leave;
  }

  /** Makes the transaction's writes durable and gives the turn back. If the commit fails, nothing is kept. */
  async commit(): Promise<void> {
    try {
      await this.#client.query('COMMIT');
    } catch (error) {
      await this.#rollbackQuietly();
      throw error;
    } finally {
      this.#giveTurnBack();
    }
  }

  /** Undoes the transaction's writes and gives the turn back. */
  async rollback(): Promise<void> {
    try {
      await this.#client.query('ROLLBACK');
    } finally {
      this.#giveTurnBack();
    }
  }

  /**
   * A value kept under `name`, the same for every server on the database: `make()` is called only when there is
   * none yet, and the one that lands first is kept (ADR 2). Used for what must not differ between servers,
   * such as the key tokens are signed with.
   */
  async setting(name: string, make: () => string): Promise<string> {
    const read = () =>
      this.read(
        db =>
          db.prepare('SELECT value FROM settings WHERE name = ?').get(name) as Promise<{ value: string } | undefined>,
      );
    const existing = await read();
    if (existing) return existing.value;
    await this.writeAlone(db =>
      db.prepare('INSERT INTO settings (name, value) VALUES (?, ?) ON CONFLICT DO NOTHING').run(name, make()),
    );
    const kept = await read();
    if (!kept) throw new Error(`The setting ${name} was not kept`);
    return kept.value;
  }

  async close(): Promise<void> {
    await this.#client.end().catch(() => undefined);
    await this.#pool.end().catch(() => undefined);
  }

  async #prepare(schema: readonly string[], before?: (database: Queryable) => Promise<void>): Promise<void> {
    const client = this.#client;
    await client.query('BEGIN');
    try {
      await client.query('SELECT pg_advisory_xact_lock($1)', [PREPARATION_LOCK]);
      const empty = (await client.query(`SELECT to_regclass('settings') AS found`)).rows[0].found === null;
      for (const statement of schema) await client.query(inPostgres(statement));
      if (empty && before) {
        await before(this.#writer);
        for (const statement of schema) await client.query(inPostgres(statement));
      }
      await client.query('COMMIT');
    } catch (error) {
      await this.#rollbackQuietly();
      throw error;
    }
  }

  #takeTurn(): Promise<() => void> {
    const previous = this.#queue;
    let leave!: () => void;
    this.#queue = new Promise<void>(resolve => {
      leave = resolve;
    });
    return previous.then(() => leave);
  }

  #giveTurnBack(): void {
    const leave = this.#leave;
    this.#leave = undefined;
    leave?.();
  }

  async #rollbackQuietly(): Promise<void> {
    try {
      await this.#client.query('ROLLBACK');
    } catch {
      // The connection may be gone, and with it the transaction: nothing is left to undo.
    }
  }
}

/**
 * A statement of a schema, written once, in the form the stores read: an integer is a 64-bit one, a key that counts is an identity,
 * and text is compared and ordered by its bytes, as every key and every month the application keeps is written to be (the database's
 * collation would order 'a-b' and 'ab' as its locale likes).
 */
function inPostgres(statement: string): string {
  return statement
    .replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/g, 'BIGINT')
    .replace(/\bTEXT\b(?! COLLATE)/g, 'TEXT COLLATE "C"');
}
